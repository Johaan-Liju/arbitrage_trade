import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';

const base = process.env.GOLDLENS_TEST_URL || 'http://127.0.0.1:3000';
const api = process.env.GOLDLENS_TEST_API || base;
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/api/**', async route => {
    const url = new URL(route.request().url());
    await route.fulfill({response: await route.fetch({url: `${api}${url.pathname}${url.search}`})});
  });
  // Cover the actual default pair before the example that generates trades.
  await page.goto(`${base}/backtest`);
  await expect(page.getByRole('button', {name:'Run simulation'})).toBeVisible();
  const noTradeResponse = page.waitForResponse(r => r.url().endsWith('/api/backtest'));
  await page.getByRole('button', {name:'Run simulation'}).click();
  const noTrade = await (await noTradeResponse).json();
  assert.equal(noTrade.config.contract_a, 'GOLDM:2026-11-20:demo-v4');
  assert.equal(noTrade.number_of_trades, 0);
  assert.equal(noTrade.diagnostics.entry_signals, 0);
  assert.ok(noTrade.diagnostics.peak_abs_z < noTrade.config.entry_z);
  await expect(page.getByTestId('simulation-reason')).toContainText('below your entry threshold');
  await expect(page.getByTestId('simulation-result')).toBeFocused();
  await expect(page.getByTestId('simulation-result')).toContainText('no trades opened');
  await page.getByRole('link', {name:'Load synthetic example'}).click();
  await expect(page.getByRole('button', {name:'Run simulation'})).toBeVisible();
  const exampleResponse = page.waitForResponse(r => r.url().endsWith('/api/backtest'));
  await page.getByRole('button', {name:'Run simulation'}).click();
  const example = await (await exampleResponse).json();
  assert.equal(example.config.contract_a, 'GOLDTEN:2026-11-20:demo-v4');
  assert.ok(example.number_of_trades > 0);
  await expect(page.getByTestId('simulation-result')).toHaveText('Simulation results');
  console.log('PASS default pair: zero trades explained with actual threshold statistics; explicit synthetic example produces completed trades');
  await expect(page.getByRole('button', {name:'Run simulation'})).toBeVisible();
  await page.getByLabel('Maximum holding calendar days', {exact:true}).fill('3');
  await page.getByText('Additional costs by leg', {exact:true}).click();
  await page.getByLabel('Leg A: assumed tax bps', {exact:true}).fill('2');
  await page.getByLabel('Leg B: assumed fixed inr', {exact:true}).fill('7');
  const response = page.waitForResponse(r => r.url().endsWith('/api/backtest'));
  await page.getByRole('button', {name:'Run simulation'}).click();
  const result = await response;
  assert.equal(result.status(),200);
  const run = await result.json();
  assert.equal(run.config.max_holding_days,3);
  assert.equal(run.config.costs_a.tax_bps,2);
  assert.equal(run.config.costs_b.fixed_inr,7);
  assert.ok(run.trades.length > 0);
  assert.ok(run.trades.every(t => t.entry_fill_at > t.signal_available_at && t.exit_fill_at > t.exit_signal_available_at));
  assert.ok(Math.abs(run.realized_net_pnl - run.trades.reduce((sum,t) => sum+t.net_pnl,0))<1e-8);
  await expect(page.getByText('Realized net P&L / INR', {exact:true})).toBeVisible();
  await expect(page.getByText('Open position (excluded from realized results)', {exact:true})).toBeVisible();
  await expect(page.getByText('Skipped signals and unfilled orders', {exact:true})).toBeVisible();
  await page.locator('summary').filter({hasText: /^Trade 1 /}).click();
  await expect(page.getByText(/Residual gross/).first()).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth<=innerWidth),true,'Trade ledger must scroll inside its card on mobile');
  await page.getByText('Change research time',{exact:false}).click();
  const nextPair=page.waitForResponse(r => r.url().endsWith('/api/pair') && r.status()===200);
  await page.fill('#asof','2026-10-06T18:00');
  await page.getByRole('button',{name:'Apply time'}).click(); await nextPair;
  await expect(page.getByRole('button',{name:'Run simulation'})).toBeVisible();
  const openResponse=page.waitForResponse(r => r.url().endsWith('/api/backtest') && r.status()===200);
  await page.getByRole('button',{name:'Run simulation'}).click();
  const open=await (await openResponse).json();
  assert.ok(open.open_position && open.open_entry_costs>0);
  assert.equal(open.realized_net_pnl,0);
  assert.equal(open.trades.length,0);
  assert.equal(open.net_pnl,null);
  await expect(page.getByText(/net of incurred entry costs INR/)).toBeVisible();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(errors,[]);
  console.log(`PASS: paired backtest controls reach API; ${run.trades.length} closed trades reconcile; later fills, assumed costs, residual exposure and skipped orders render; early cutoff leaves an open position with costs separate from zero realized P&L; mobile ledger has no page overflow; no browser errors`);
} finally { await browser.close(); }
